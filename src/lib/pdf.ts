"use client";

import { recognizeImageText, type OcrProgress } from "./ocr";

const MAX_PAGES = 6;
const MIN_TEXT_LENGTH_TO_SKIP_OCR = 40;

type PdfJsModule = typeof import("pdfjs-dist");

let pdfjsPromise: Promise<PdfJsModule> | null = null;

async function getPdfjs(): Promise<PdfJsModule> {
  if (!pdfjsPromise) {
    pdfjsPromise = import("pdfjs-dist").then((mod) => {
      // Bundler-native worker asset — no external CDN dependency, works
      // the same offline or online.
      mod.GlobalWorkerOptions.workerSrc = new URL(
        "pdfjs-dist/build/pdf.worker.min.mjs",
        import.meta.url,
      ).toString();
      return mod;
    });
  }
  return pdfjsPromise;
}

export async function extractTextFromPdf(
  file: File,
  onProgress?: (p: OcrProgress) => void,
): Promise<string> {
  onProgress?.({ status: "reading pdf", progress: 0.02 });
  const pdfjs = await getPdfjs();
  const buffer = await file.arrayBuffer();
  const doc = await pdfjs.getDocument({ data: buffer }).promise;
  const pageCount = Math.min(doc.numPages, MAX_PAGES);

  // Pass 1: try the embedded text layer — instant and reliable for any
  // PDF generated by a computer (CNSS, ANAPEC, impôts... almost never
  // scanned images).
  let textLayerContent = "";
  for (let i = 1; i <= pageCount; i++) {
    const page = await doc.getPage(i);
    const content = await page.getTextContent();
    const pageText = content.items.map((it) => ("str" in it ? it.str : "")).join(" ");
    textLayerContent += `${pageText}\n`;
    onProgress?.({ status: "recognizing text", progress: (i / pageCount) * 0.5 });
  }

  if (textLayerContent.trim().length >= MIN_TEXT_LENGTH_TO_SKIP_OCR) {
    onProgress?.({ status: "recognizing text", progress: 1 });
    return textLayerContent.trim();
  }

  // Pass 2: no usable text layer — this PDF is a scanned image. Render
  // each page to a canvas and run the same OCR engine used for photos.
  let ocrText = "";
  for (let i = 1; i <= pageCount; i++) {
    const page = await doc.getPage(i);
    const viewport = page.getViewport({ scale: 2 });
    const canvas = document.createElement("canvas");
    canvas.width = viewport.width;
    canvas.height = viewport.height;
    const ctx = canvas.getContext("2d");
    if (!ctx) continue;
    await page.render({ canvasContext: ctx, viewport }).promise;

    const blob: Blob | null = await new Promise((resolve) => canvas.toBlob(resolve, "image/png"));
    if (!blob) continue;

    const pageText = await recognizeImageText(blob, (p) => {
      const base = 0.5 + ((i - 1) / pageCount) * 0.5;
      const pageShare = p.progress / pageCount;
      onProgress?.({ status: p.status, progress: Math.min(0.99, base + pageShare * 0.5) });
    });
    ocrText += `${pageText}\n`;
  }

  onProgress?.({ status: "recognizing text", progress: 1 });
  return ocrText.trim();
}
